function sendFailure(req, res, error) {
  req.session = null; // Never implicitly save/touch stale or uncertain state.
  const code = Object.hasOwn(STATUS, error?.code) ? error.code : 'AUTH_UNAVAILABLE';
  res.set('Cache-Control', 'no-store');
  return res.status(STATUS[code]).json({ success: false, code, error: code });
}
module.exports = { sendFailure };
