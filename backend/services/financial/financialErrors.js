function sendFailure(req, res, error) {
  req.session = null; // unset:'keep': suppress stale save/touch, NOT destroy.
  const code = Object.hasOwn(STATUS, error?.code) ? error.code : 'FINANCIAL_UNAVAILABLE';
  let status = STATUS[code];
  if (code === 'INVALID_PAYMENT_UPLOAD' && error.status === 413) status = 413;
  const body = { success: false, code, error: code };
  if (code === 'FINANCIAL_OUTCOME_UNKNOWN' ||
      ['FINANCIAL_UNAVAILABLE', 'FINANCIAL_RETRY_EXHAUSTED'].includes(code) && error.retryWithSameKey === true) body.retryWithSameKey = true;
  if (code === 'PAYMENT_SUBMISSION_OUTCOME_UNKNOWN') {
    if (/^pay-[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/.test(error.paymentId || '')) body.paymentId = error.paymentId;
    body.retrySubmission = false;
  }
  res.set('Cache-Control', 'no-store');
  return res.status(status).json(body);
}
